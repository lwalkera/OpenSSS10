#!/usr/bin/env python3
"""Generate src/tables.c: integer lookup tables for the sound and light levels.

The stock firmware evaluates these formulas with soft-float log10 (spec §11.4,
§11.5). Precomputing them keeps libm out of the 28 KB image. Values are
truncated toward zero, as a float-to-int conversion would.
"""
import math


def sound_level(avgdev):
    if avgdev < 20:
        level = 20 + 38 * math.log10(1 + 0.3 * avgdev)
    else:
        level = 57 + 50 * math.log10(0.4 + 0.02 * avgdev)
    return min(int(level), 100)


def light_level(x):
    if x < 301:
        level = 30 * math.log10(x + 1)
    else:
        level = 50 * math.log10(x / 10.0 + 1)
    return min(int(level), 100)


def sound_table():
    table = []
    avgdev = 0
    while True:
        table.append(sound_level(avgdev))
        if table[-1] >= 100:
            return table
        avgdev += 1


def emit(name, size_macro, values):
    print(f"const uint8_t {name}[{size_macro}] = {{")
    for i in range(0, len(values), 16):
        print("  " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    print("};")
    print()


def main():
    sound = sound_table()
    light = [light_level(x) for x in range(1024)]
    print("/* Generated by tools/gen_tables.py - do not edit */")
    print('#include "tables.h"')
    print()
    print("/* Sound level 0..100 indexed by mean absolute deviation; saturates at the end */")
    assert len(sound) == 344, "update SOUND_TABLE_LEN in src/tables.h"
    emit("sound_level_table", "SOUND_TABLE_LEN", sound)
    print("/* Light level 0..100 indexed by x = 1023 - adc */")
    emit("light_level_table", "LIGHT_TABLE_LEN", light)


if __name__ == "__main__":
    main()
